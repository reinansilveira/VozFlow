import { describe, expect, it, vi } from 'vitest';
import type { WhatsAppApi, WhatsAppChatApi } from './wpp-api';
import { generateMessageId, getExistingMessageState, messageIdTargetsChat } from './wpp-idempotency';

const createWpp = (chatOverrides: Partial<WhatsAppChatApi>): WhatsAppApi => ({
  loader: {
    injectLoader: () => undefined,
    onReady: () => undefined,
  },
  chat: {
    getActiveChat: () => undefined,
    sendFileMessage: async () => ({ id: 'file', ack: 1, sendMsgResult: { messageSendResult: 'OK' } }),
    sendTextMessage: async () => ({ id: 'text', ack: 1, sendMsgResult: { messageSendResult: 'OK' } }),
    markIsRecording: async () => undefined,
    markIsComposing: async () => undefined,
    markIsPaused: async () => undefined,
    ...chatOverrides,
  },
});

describe('scheduled message idempotency', () => {
  it('detects whether a persisted message id belongs to the resolved chat', () => {
    expect(messageIdTargetsChat('true_contact@lid_ABCDEF', 'contact@lid')).toBe(true);
    expect(messageIdTargetsChat('true_5511999999999@c.us_ABCDEF', 'contact@lid')).toBe(false);
  });

  it('uses the message key generated by WhatsApp for the resolved chat', async () => {
    const wpp = createWpp({
      generateMessageID: vi.fn().mockResolvedValue({
        toString: () => 'true_5511999999999@c.us_ABCDEF',
      }),
    });

    await expect(generateMessageId(wpp, '5511999999999@c.us'))
      .resolves.toBe('true_5511999999999@c.us_ABCDEF');
  });

  it('rejects a key that does not belong to the resolved chat', async () => {
    const wpp = createWpp({
      generateMessageID: vi.fn().mockResolvedValue('true_other@lid_ABCDEF'),
    });

    await expect(generateMessageId(wpp, 'contact@lid')).rejects.toThrow('inválido');
  });

  it.each([
    [undefined, 'missing'],
    [{ ack: 0 }, 'pending'],
    [{ ack: 1 }, 'confirmed'],
    [{ ack: 3 }, 'confirmed'],
    [{ ack: -1 }, 'failed'],
  ] as const)('classifies a previously prepared message %#', async (message, expectedState) => {
    const wpp = createWpp({ getMessageById: vi.fn().mockResolvedValue(message) });
    await expect(getExistingMessageState(wpp, 'message-id')).resolves.toBe(expectedState);
  });

  it('treats a message missing from the local store as safe to send with the same id', async () => {
    const wpp = createWpp({ getMessageById: vi.fn().mockRejectedValue({ code: 'msg_not_found' }) });
    await expect(getExistingMessageState(wpp, 'message-id')).resolves.toBe('missing');
  });

  it('stops a retry when the previous message cannot be checked safely', async () => {
    const wpp = createWpp({ getMessageById: vi.fn().mockRejectedValue({ code: 'store_unavailable' }) });
    await expect(getExistingMessageState(wpp, 'message-id')).rejects.toThrow('store_unavailable');
  });
});
